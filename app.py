class Application(BaseHTTPRequestHandler):
    """Routes a request to the component that owns its path.

    The component's handler is given the request as though it had been serving
    alone: constructed without running `__init__`, with this request's own
    attributes copied onto it, and entered through `do_GET`/`do_POST` — the
    shape every `BaseHTTPRequestHandler` has, rather than any private method a
    particular scaffold happens to define. That is what lets components written
    to be standalone services share a port without being rewritten.
    """

    def log_message(self, *args):
        pass

    def _send(self, status, payload=None):
        body = b"" if status == 204 else json.dumps(payload).encode()
        self.send_response(status)
        if body:
            self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        if body:
            self.wfile.write(body)

    def do_GET(self):
        self._dispatch("GET")

    def do_POST(self):
        self._dispatch("POST")

    def do_PUT(self):
        self._dispatch("PUT")

    def do_DELETE(self):
        self._dispatch("DELETE")

    def _dispatch(self, method):
        path = self.path.split("?", 1)[0]
        if path.rstrip("/") == "/health":
            return self._send(200, {
                "service": SERVICE_NAME,
                "version": SERVICE_VERSION,
                "components": [component["service"] for component in COMPONENTS],
                # What is switched on right now. A release that did nothing and
                # a release that was never applied look identical without it.
                "flags": flags.all_on(),
            })

        for component in COMPONENTS:
            base = component["base_path"]
            if path != base and not path.startswith(base + "/"):
                continue
            for verb, pattern, flag in component["routes"]:
                if verb != method or not re.match(pattern, path):
                    continue
                if flag and not flags.on(flag):
                    # Dark (D-26). Merged, deployed, and not yet released: the
                    # endpoint does not exist as far as any caller can tell.
                    return self._send(404, {"error": "not found"})
                return self._delegate(component["handler"], method)
            # The component owns the prefix and does not serve this operation.
            return self._send(404, {"error": "not found"})
        self._send(404, {"error": "not found"})

    def _delegate(self, handler_class, method):
        entry = getattr(handler_class, "do_" + method, None)
        if entry is None:
            return self._send(405, {"error": "method not allowed"})
        delegate = handler_class.__new__(handler_class)
        delegate.__dict__.update(self.__dict__)
        try:
            entry(delegate)
        finally:
            # The component decides whether the connection survives its reply.
            self.close_connection = getattr(
                delegate, "close_connection", self.close_connection
            )


def serve(port=PORT):
    ThreadingHTTPServer(("0.0.0.0", port), Application).serve_forever()


