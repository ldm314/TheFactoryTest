import json
import os

import flags
import uvicorn
from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse
from foundation import router as foundation_router

SERVICE_NAME = 'Factory Test 4'
SERVICE_VERSION = "1.0.0"
PORT = int(os.environ.get("PORT", "8080"))

COMPONENTS = [
    {"service": 'foundation', "base_path": '/foundation', "routes": [('GET', '^/foundation/?$', '')]},
]

app = FastAPI(title=SERVICE_NAME, version=SERVICE_VERSION)
app.include_router(foundation_router)


@app.get("/health")
async def application_health():
    return {
        "service": SERVICE_NAME,
        "version": SERVICE_VERSION,
        "components": [component["service"] for component in COMPONENTS],
        "flags": flags.all_on(),
    }


@app.middleware("http")
async def enforce_flags(request: Request, call_next):
    path = request.url.path.split("?", 1)[0]
    for component in COMPONENTS:
        base = component["base_path"]
        if path != base and not path.startswith(base + "/"):
            continue
        for verb, pattern, flag in component["routes"]:
            import re
            if request.method != verb or not re.match(pattern, path):
                continue
            if flag and not flags.on(flag):
                return JSONResponse(status_code=404, content={"error": "not found"})
            break
    return await call_next(request)


if __name__ == "__main__":
    print(json.dumps({
        "service": SERVICE_NAME,
        "port": PORT,
        "components": [c["service"] for c in COMPONENTS],
        "flags_on": flags.all_on(),
    }))
    uvicorn.run(app, host="0.0.0.0", port=PORT)
