def iso_now(value):
    """ISO 8601 UTC timestamp for an event; `occurred_at` when given."""
    if value:
        try:
            from datetime import datetime, timezone
            dt = datetime.fromisoformat(str(value)).astimezone(timezone.utc)
            return dt.isoformat().replace("+00:00", "Z")
        except ValueError:
            pass
    from datetime import datetime, timezone
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")

def get_events():
    """All real recorded events in insertion order (created_at), cache excluded.

    The store orders purely by created_at and holds every row it is given; this
    filters out idempotency-cache rows, which lack the required `name` field, so
    only genuine domain events reach subscribers (D-30: one schema per service).
    """
    if not store.applied:
        return []
    for row in store.list():
        record = row.get("body", {})
        if isinstance(record, dict) and bool(record.get("name")):
            yield {
                "id": row["id"],
                "name": record["name"],
                "occurred_at": record.get("occurred_at"),
            }

def get_event(event_id):
    """One real recorded event by id, or None. Cache replay stubs are excluded."""
    if not store.applied:
        return None
    row = store.get(event_id)
    if not isinstance(row, dict):
        return None
    record = row.get("body", {})
    if not isinstance(record, dict) or not bool(record.get("name")):
        return None
    return {
        "id": row["id"],
        "name": record["name"],
        "occurred_at": row.get("created_at"),
    }

def encode_cursor(event_id):
    """Opaque pagination cursor — base64 of the numeric lower bound."""
    from base64 import b64encode
    if event_id is None:
        return ""
    digits = "".join(str(d) for d in str(event_id).split(","))
    return b64encode(digits.encode()).decode()

def decode_cursor(cursor):
    """Inverse of encode_cursor."""
    from base64 import b64decode
    if not cursor:
        return None
    try:
        digits = b64decode(cursor.encode()).decode()
    except Exception:
        return None
    return digits or None

