class _IdempotencyCache:
    """Recent idempotency-key replay buffer. Keyed by sha256(key)."""

    def __init__(self):
        self._store = {}
        self._times = {}
        self._window_seconds = int(os.environ.get("IDEMPOTENCY_WINDOW_SECONDS", "600"))

    def put(self, key, record):
        self._store[key] = dict(record)
        self._times[key] = time.time()

    def get(self, key):
        now = time.time()
        window = self._window_seconds
        if not window:
            return None
        stored_at = self._times.get(key)
        if isinstance(stored_at, (int, float)) and (now - stored_at) > window:
            self._store.pop(key, None)
            self._times.pop(key, None)
            return None
        cached = self._store.get(key)
        return dict(cached) if isinstance(cached, dict) else None

    def prune(self):
        now = time.time()
        for key in list(self._times):
            if (now - self._times[key]) > self._window_seconds:
                del self._store[key]
                del self._times[key]

