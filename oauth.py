def generate_authcode() -> str:
    """Produce a cryptographically secure single-use code string."""
    return secrets.token_urlsafe(32)

def _client_redirect_uri(client_id):
    record = store.get(client_id)
    if not record:
        return None
    value = record.get('redirect_uri')
    return value if isinstance(value, str) else None

def is_code_expired(issued_at, now=None) -> bool:
    """True when a code's 10-minute validity window has passed."""
    if now is None:
        now = clock.now()
    start = float(issued_at.timestamp() if hasattr(issued_at, 'timestamp') else issued_at)
    return (float(now) - start) > AUTH_CODE_TTL_SECONDS

def validate_scope_match(requested_scopes, bound_scopes) -> bool:
    """True when the requested scopes are covered by those bound to the code."""
    if not isinstance(bound_scopes, list):
        return False
    for scope in requested_scopes or []:
        if scope not in bound_scopes:
            return False
    return True

def mark_code_redeemed(code) -> None:
    """Record single-use redemption; the first use consumes the code."""
    _issued.pop(code, None)

AUTH_CODE_TTL_SECONDS = 600

TOKEN_EXPIRES_IN = 3600

_issued = {}
